import type * as React from "react";

/* ────────────────────────────────────────────────────────────────────────────
 * สถานะของแถวตัวเลือกที่ส่งให้ `renderOption`
 *
 * ใช้ร่วมกันทั้ง ComboBox · MultiAutocomplete · EntityAutocomplete —
 * ถ้าแต่ละตัวส่งคนละทรง คนที่เขียนแถวเองจะต้องจำว่า component ไหนให้อะไรบ้าง
 * ──────────────────────────────────────────────────────────────────────────── */

export type OptionRowState = {
  /** ถูกเลือกอยู่ */
  selected: boolean;
  /**
   * ล็อกไว้ — เลือกอยู่แล้วและถอดออกไม่ได้
   *
   * 🔴 ต่างจาก `disabled` ตรงที่ **ถูกเลือกอยู่เสมอ** · `disabled` คือกดไม่ได้
   * เพราะเลือกไม่ได้ ส่วน `locked` คือกดไม่ได้เพราะเอาออกไม่ได้
   */
  locked: boolean;
  /** กดไม่ได้ — ปิดใช้งานมาเอง หรือเลือกครบเพดาน `maxItems` แล้ว */
  disabled: boolean;
};

/**
 * สถานะที่ส่งให้ `renderChip` (เฉพาะโหมดเลือกหลายอัน)
 *
 * แยกจาก `OptionRowState` เพราะ chip ไม่มีสถานะ "ถูกเลือก" (อยู่บน chip แปลว่าเลือกแล้ว)
 * และไม่มี "กดไม่ได้"
 */
export type ChipState = {
  /** ถอดออกไม่ได้ — ต้องบอกผู้ใช้ด้วยว่าทำไม ไม่ใช่แค่ซ่อนปุ่ม × */
  locked: boolean;
  /**
   * ถอดตัวนี้ออก — ผูกกับปุ่ม × ของ chip ที่วาดเอง · `undefined` เมื่อ `locked`
   *
   * 🔴 เดิมไม่มี ⇒ **chip ที่วาดเองถอดออกไม่ได้เลย** (ปุ่ม × ไม่มีอะไรให้เรียก) ผู้เรียกที่อยากได้แค่
   * avatar บน chip ต้องเลือกระหว่าง "สวยแต่ลบไม่ได้" กับ "ลบได้แต่หน้าตา default"
   * (พบตอนย้าย `MultiSelectAutocomplete` ของ Mediwork มาใช้ DS: 7 จอวาด chip เองพร้อม `onDelete`)
   *
   * หยุด event ไม่ให้ไปถึงตัวช่องให้แล้ว — ไม่งั้นกด × แล้วแผงตัวเลือกเปิดตามขึ้นมาด้วย
   */
  onRemove?: (event: React.SyntheticEvent) => void;
};
